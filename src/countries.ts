const build = (): Readonly<Record<string, Specification>> => {
  const table: Record<string, Specification> = Object.create(null) as Record<string, Specification>;
  for (const [code, length, structure, example, sepa] of OFFICIAL) {
    table[code] = new Specification(code, length, structure, example, true, sepa === true);
  }
  for (const [code, length, structure, example] of UNOFFICIAL) {
    table[code] = new Specification(code, length, structure, example, false, false);
  }
  return Object.freeze(table);
};

/**
 * Map of ISO country codes to their IBAN specifications. Frozen and prototype-less.
 */
export const countries: Readonly<Record<string, Specification>> = build();
